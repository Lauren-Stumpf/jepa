"""
Write the configs for the frozen-encoder fine-tuning experiment (10% of the organic
training pairs). Every config is a copy of the existing plain-variant 10% fine-tune
config for the same seed, with only these lines changed, so nothing else can differ
from the runs already done:

  wandb name, num_epochs, finetune read_from, finetune method (+ its heads config)

Two starting encoders:
  random   untrained encoder, results/runs/random_encoder_organic8_s<seed>
           (train/make_random_checkpoint.py)
  plain    the plain-variant pretrained encoder, results/runs/jepa_pretrain_plain_organic8

Two procedures (the third, everything trains from step 1, is already done):
  A  frozen     encoder fixed for all 100 epochs; only the heads train     (seed 0 only)
  B  heads first: stage 1, 10 epochs heads only; stage 2, 90 epochs everything,
                  starting from stage 1's LAST epoch (model_last.ckpt,      (seeds 0, 1, 2)
                  made by train/last_epoch_checkpoint.py; metatrain would otherwise load the best epoch)

  python scripts/make_frozen_configs.py
"""

import os
import re

REPO = "/storage3/lauren/code/jepa"
HERE = os.path.join(os.path.dirname(__file__), "..")
START = {
    "random": REPO + "/results/runs/random_encoder_organic8_s{seed}/pretrained.ckpt",
    "plain": REPO + "/results/runs/jepa_pretrain_plain_organic8/pretrained.ckpt",
}
HEADS = ("      method: heads           # encoder frozen: only the output heads and last layers train\n"
         "      config:\n"
         "        head_modules: [node_heads, edge_heads]\n"
         "        last_layer_modules: [node_last_layers, edge_last_layers]")


def make(seed, name, epochs, read_from, method, note):
    src = os.path.join(HERE, f"configs/jepa_finetune_plain_organic8_10pct_s{seed}.yaml")
    text = open(src).read()
    rules = [
        (r"^  name: jepa_finetune_plain_organic8_10pct_s\d+$", f"  name: {name}"),
        (r"^    num_epochs: 100 .*$", f"    num_epochs: {epochs}"),
        (r"^      read_from: /storage3/\S+.*$", f"      read_from: {read_from}"),
        (r"^      method: full .*$", HEADS if method == "heads" else "      method: full            # every weight trains"),
    ]
    for pat, new in rules:
        text, n = re.subn(pat, new, text, flags=re.M)
        assert n == 1, f"{src}: expected exactly one line matching {pat}, found {n}"
    header = f"# Frozen-encoder experiment: {note}\n# Generated by scripts/make_frozen_configs.py from {os.path.basename(src)}.\n"
    with open(os.path.join(HERE, f"configs/{name}.yaml"), "w") as f:
        f.write(header + text)
    return name


def main():
    made = []
    for start in ("random", "plain"):
        # A: frozen for all 100 epochs (control), seed 0
        made.append(make(0, f"frozen_{start}_organic8_10pct_s0", 100, START[start].format(seed=0), "heads",
                         f"procedure A (encoder frozen for all 100 epochs), {start} encoder"))
        # B: heads first, then everything
        for seed in (0, 1, 2):
            s1 = f"headsfirst1_{start}_organic8_10pct_s{seed}"
            made.append(make(seed, s1, 10, START[start].format(seed=seed), "heads",
                             f"procedure B stage 1 (heads only, 10 epochs), {start} encoder"))
            made.append(make(seed, f"headsfirst2_{start}_organic8_10pct_s{seed}", 90,
                             f"{REPO}/results/runs/{s1}/model_last.ckpt", "full",
                             f"procedure B stage 2 (everything, 90 epochs) from the end of {s1}"))
    print("\n".join(made))


if __name__ == "__main__":
    main()
