"""
Write the configs for the water pretraining experiment at the 16 fs stride, mirroring
the organic one. Every config is a copy of configs/flashmd_water16_scratch.yaml (the
300-epoch full-data water baseline) with only these lines changed:

  seed, wandb name, num_epochs (100, as for organic), training-set file (10% subset),
  and, for fine-tunes, a finetune block (read_from the water pretraining, method full)

  flashmd_water16_scratch_10pct_s<seed>             baseline, 10% of the pairs, seeds 0 1 2
  jepa_finetune_<variant>_water16_10pct_s<seed>     fine-tune of each pretraining variant, seeds 0 1 2

  python scripts/make_water16_configs.py
"""

import os
import re

REPO = "/storage3/lauren/code/jepa"
HERE = os.path.join(os.path.dirname(__file__), "..")
VARIANTS = ["plain", "normtarget", "resid", "proj", "residrel"]
FINETUNE = ("    finetune:\n"
            "      read_from: {ckpt}\n"
            "      method: full            # every weight trains, same as the baseline\n")


def make(name, seed, note, finetune_ckpt=None):
    src = os.path.join(HERE, "configs/flashmd_water16_scratch.yaml")
    text = open(src).read()
    rules = [
        (r"^seed: 0$", f"seed: {seed}"),
        (r"^  name: flashmd_water16_scratch$", f"  name: {name}"),
        (r"^    num_epochs: 300$", "    num_epochs: 100          # as the organic 10% comparison"),
        (r"^(training_set:\n  systems:\n    read_from: )data/water/pairs/16fs/train\.xyz$",
         r"\1data/water/pairs/16fs/train_10pct.xyz"),
    ]
    if finetune_ckpt:
        rules.append((r"^(    checkpoint_interval: .*\n)", r"\1" + FINETUNE.format(ckpt=finetune_ckpt).replace("\\", "\\\\")))
    for pat, new in rules:
        text, n = re.subn(pat, new, text, flags=re.M)
        assert n == 1, f"expected exactly one match for {pat!r}, found {n}"
    text = f"# {note}\n# Generated by scripts/make_water16_configs.py from flashmd_water16_scratch.yaml.\n" + text
    with open(os.path.join(HERE, f"configs/{name}.yaml"), "w") as f:
        f.write(text)
    return name


def main():
    made = []
    for seed in (0, 1, 2):
        made.append(make(f"flashmd_water16_scratch_10pct_s{seed}", seed,
                         "Water 16 fs baseline on 10% of the training pairs (from random weights)"))
        for v in VARIANTS:
            made.append(make(f"jepa_finetune_{v}_water16_10pct_s{seed}", seed,
                             f"Water 16 fs fine-tune of the {v} pretraining on 10% of the training pairs",
                             f"{REPO}/results/runs/jepa_pretrain_{v}_water16/pretrained.ckpt"))
    print("\n".join(made))


if __name__ == "__main__":
    main()
