"""
Write the configs and run lists for two experiments (cards in experiments/E05 and experiments/E06).

E05, hypothesis A: does the water pretraining gain last with ten times more training?
  Copies of the water 16 fs 10% configs (baseline, plain, normalised target; seeds 0 1 2)
  with num_epochs 100 -> 1000. Nothing else changes.

E06, hypothesis B: does the water gain come from the regulariser rather than from prediction?
  One pretraining identical to jepa_pretrain_plain_water16 except --w_inv 0 (no prediction
  term), then fine-tunes that are copies of jepa_finetune_plain_water16_10pct_s<seed> reading
  that pretraining instead. Nothing else changes.

Every config logs to the Weights and Biases project jepa-flashmd-experiments with
group = experiment id and job_type = arm, so runs group by experiment and arm.

  python scripts/make_e05_e06.py
"""

import os
import re

REPO = "/storage3/lauren/code/jepa"
HERE = os.path.join(os.path.dirname(__file__), "..")
PROJECT = "jepa-flashmd-experiments"
WATER = "CONFIG=configs/flashmd_water16_scratch.yaml TRAIN=data/water/pairs/16fs/train.xyz VAL=data/water/pairs/16fs/val.xyz"


def copy_config(src, name, group, job_type, rules, note):
    text = open(os.path.join(HERE, "configs", src)).read()
    rules = [(r"^wandb:\n  project: \S+\n  name: \S+$",
              f"wandb:\n  project: {PROJECT}\n  name: {name}\n  group: {group}\n  job_type: {job_type}")] + rules
    for pat, new in rules:
        text, n = re.subn(pat, new, text, flags=re.M)
        assert n == 1, f"{src}: expected one match for {pat!r}, found {n}"
    text = f"# {group}: {note}\n# Generated by scripts/make_e05_e06.py from {src}.\n" + text
    with open(os.path.join(HERE, "configs", f"{name}.yaml"), "w") as f:
        f.write(text)


def main():
    os.makedirs(os.path.join(HERE, "experiments/E05"), exist_ok=True)
    os.makedirs(os.path.join(HERE, "experiments/E06"), exist_ok=True)

    # E05: same runs, 1000 epochs
    lines = []
    for arm, src in (("baseline", "flashmd_water16_scratch_10pct_s{s}.yaml"),
                     ("plain", "jepa_finetune_plain_water16_10pct_s{s}.yaml"),
                     ("normtarget", "jepa_finetune_normtarget_water16_10pct_s{s}.yaml")):
        for s in (0, 1, 2):
            name = f"e05_{arm}_water16_10pct_1000ep_s{s}"
            copy_config(src.format(s=s), name, "E05", arm,
                        [(r"^    num_epochs: 100 .*$", "    num_epochs: 1000       # E05: ten times the 100-epoch runs")],
                        f"{arm}, seed {s}, 1000 epochs")
            lines.append(f"{name}|train|40000|1|configs/{name}.yaml")
    with open(os.path.join(HERE, "experiments/E05/runs.txt"), "w") as f:
        f.write("# name|kind|min GPU memory (MB)|runs per GPU|spec   (scripts/launch_runs.sh)\n" + "\n".join(lines) + "\n")

    # E06: regulariser-only pretraining, then fine-tunes
    pre = "e06_pretrain_regonly_water16"
    lines = [f"{pre}|pretrain|20000|1|{WATER} -- --batch_size 8 --predictor plain --w_inv 0 "
             f"--wandb {PROJECT} --wandb_group E06 --wandb_job_type pretrain-regonly"]
    for s in (0, 1, 2):
        name = f"e06_finetune_regonly_water16_10pct_s{s}"
        copy_config(f"jepa_finetune_plain_water16_10pct_s{s}.yaml", name, "E06", "regonly",
                    [(r"^      read_from: /storage3/\S+/jepa_pretrain_plain_water16/pretrained\.ckpt$",
                      f"      read_from: {REPO}/results/runs/{pre}/pretrained.ckpt")],
                    f"fine-tune of the regulariser-only pretraining, seed {s}")
        lines.append(f"{name}|train|40000|1|configs/{name}.yaml")
    with open(os.path.join(HERE, "experiments/E06/runs.txt"), "w") as f:
        f.write("# name|kind|min GPU memory (MB)|runs per GPU|spec   (scripts/launch_runs.sh)\n" + "\n".join(lines) + "\n")
    print("written: configs/e05_*.yaml, configs/e06_*.yaml, experiments/E05/runs.txt, experiments/E06/runs.txt")


if __name__ == "__main__":
    main()
